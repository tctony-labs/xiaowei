import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { run, targetDirectory } from "../../crates/xiaowei-mobile/ffi/scripts/ios-build.mjs";

const { values } = parseArgs({
  options: { configuration: { type: "string", default: "Debug" } },
});
const root = fileURLToPath(new URL("../../", import.meta.url));
const base = await readFile(join(root, "ios/Config/Base.xcconfig"), "utf8");
const version = base.match(/^IPHONEOS_DEPLOYMENT_TARGET\s*=\s*(\d+\.\d+)\s*$/m)?.[1];
if (!version) throw new Error("Base.xcconfig must declare a literal iOS deployment version");

await run(process.execPath, [
  join(root, "crates/xiaowei-mobile/ffi/scripts/build-ios.mjs"),
  "--deployment-target",
  version,
  "--configuration",
  values.configuration,
]);
const target = await targetDirectory();
const output = join(root, "target/ios");
await mkdir(output, { recursive: true });
await writeFile(
  join(output, "Native.xcconfig"),
  [
    "// Generated by ios/scripts/prepare.mjs; do not edit.",
    `XIAOWEI_NATIVE_DEBUG_ROOT = ${join(target, "mobile-ios/debug")}`,
    `XIAOWEI_NATIVE_RELEASE_ROOT = ${join(target, "mobile-ios/release")}`,
    "",
  ].join("\n"),
);
console.log(`iOS ${values.configuration} native dependencies prepared for iOS ${version}+`);
